-- 5.. Display those tests where no applicant has failed. 
SELECT *
FROM ENTRANCE_TEST
WHERE ET_ID NOT IN
(
    SELECT E.ET_ID
    FROM ENTRANCE_TEST E
    JOIN ETEST_DETAILS D ON E.ET_ID = D.ET_ID
    WHERE D.SCORE < E.CUT_SCORE
);

-- 6.Display details of entrance test centers which had full attendance between 1stNovember and  15	November 2011
SELECT C.*
FROM ETEST_CENTRE C
JOIN ETEST_DETAILS D ON C.ETC_ID = D.ETC_ID
WHERE D.ETEST_DATE BETWEEN '2011-11-01' AND '2011-11-15'
GROUP BY C.ETC_ID, C.LOCATION, C.INCHARGE, C.CAPACITY
HAVING COUNT(D.AID) = C.CAPACITY;


-- 7. Display the details of those applicants who have scored more than the cut-off score in the tests they have appeared in. 
SELECT A.*
FROM APPLICANT A
JOIN ETEST_DETAILS D ON A.AID = D.AID
JOIN ENTRANCE_TEST E ON D.ET_ID = E.ET_ID
WHERE D.SCORE > E.CUT_SCORE;

-- 8.Display the average and the maximum score, test wise of the tests conducted at Mumbai.
SELECT E.ET_NAME, AVG(D.SCORE) AS AVERAGE_SCORE,
       MAX(D.SCORE) AS MAXIMUM_SCORE
FROM ENTRANCE_TEST E
JOIN ETEST_DETAILS D ON E.ET_ID = D.ET_ID
JOIN ETEST_CENTRE C ON D.ETC_ID = C.ETC_ID
WHERE C.LOCATION = 'Mumbai'
GROUP BY E.ET_NAME;

-- 9.Display the number of applicants who have appeared for each test, test center wise. 
SELECT ETC_ID, ET_ID, COUNT(AID) AS NO_OF_APPLICANTS
FROM ETEST_DETAILS
GROUP BY ETC_ID, ET_ID;

SELECT C.LOCATION, T.ET_NAME, COUNT(D.AID) AS NO_OF_APPLICANTS
FROM ETEST_DETAILS D
JOIN ETEST_CENTRE C ON D.ETC_ID = C.ETC_ID
JOIN ENTRANCE_TEST T ON D.ET_ID = T.ET_ID
GROUP BY C.LOCATION, T.ET_NAME;

